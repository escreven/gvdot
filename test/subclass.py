from gvdot import Dot, impose_order
from utility import expect_str, image_format, svg_parse


def test_subclass():
    """
    An application can extend Dot and override __str__ without disrupting
    graph construction, themes, copying, ordering, or rendering.
    """
    class ApplicationDot(Dot):
        def __init__(self, *, application:str, **kwargs):
            super().__init__(**kwargs)
            self.application = application

        def __str__(self) -> str:
            return super().__str__() + f"// Generated by {self.application}\n"

    #
    # Application Dot objects can be themes.
    #

    theme = ApplicationDot(application="Theme")
    theme.node_default(shape="box")
    theme.node_role("highlight", color="red")

    for directed in (False, True):

        #
        # Application undirected and directed Dot objects can be built.
        #

        dot = ApplicationDot(application="Example", directed=directed, id="G")
        assert dot.use_theme(theme) is dot
        assert dot.graph(label="Example").node("a", role="highlight") is dot
        assert dot.edge("a", "b", label="link") is dot
        subgraph = dot.subgraph("cluster_detail")
        subgraph.node("c")
        assert subgraph.dot() is dot
        assert subgraph.parent() is dot
        assert dot.node_is_defined("a")
        assert dot.edge_is_defined("a", "b")

        #
        # They have the same string representation except as modified by the
        # application's Dot class.
        #

        kind = "digraph" if directed else "graph"
        edge = "->" if directed else "--"
        expected = f"""
        {kind} G {{
            node [shape=box]
            a [color=red]
            a {edge} b [label="link"]
            subgraph cluster_detail {{
                c
            }}
            label = "Example"
        }}
        """
        expect_str(dot, expected + "// Generated by Example\n")
        source = str(dot)
        assert source.endswith("}\n// Generated by Example\n")

        #
        # Application Dot objects can be copied.
        #

        copied = dot.copy()
        expect_str(copied, expected)
        copied.node("copy_only")
        assert not dot.node_is_defined("copy_only")
        assert str(dot) == source

        #
        # Application Dot objects can be themes for non-application Dot
        # objects.
        #

        plain = Dot().use_theme(theme).node("a", role="highlight")
        expect_str(plain, """
        graph {
            node [shape=box]
            a [color=red]
        }
        """)

        #
        # They can be rendered.
        #

        assert image_format(dot.to_rendered()) == "PNG"
        svg_parse(dot.to_svg())

        #
        # And have order imposed.
        #

        if not directed:
            ordered = impose_order(dot)
            assert ordered.node_is_defined("a")
            assert ordered.node_is_defined("c")
            assert (ordered.edge_is_defined("a", "b") or
                    ordered.edge_is_defined("b", "a"))
            svg_parse(ordered.to_svg())
            assert str(dot) == source
